from abc import ABC, abstractmethod

class ТранспортноеСредство(ABC):
    """
    Абстрактный класс, представляющий транспортное средство.
    """

    @abstractmethod
    def __init__(self, скорость: float, вместимость: int, тип_двигателя: str):
        """
        Инициализирует транспортное средство.

        Args:
            скорость (float): Максимальная скорость в км/ч. Должна быть положительной.
            вместимость (int): Количество пассажиров. Должно быть неотрицательным.
            тип_двигателя (str): Тип двигателя (например, "бензин", "электричество").

        Raises:
            ValueError: Если скорость не является положительным числом или вместимость отрицательная.
        """
        if скорость <= 0:
            raise ValueError("Скорость должна быть положительным числом.")
        if вместимость < 0:
            raise ValueError("Вместимость не может быть отрицательной.")

        self.скорость: float = скорость
        self.вместимость: int = вместимость
        self.тип_двигателя: str = тип_двигателя

    @abstractmethod
    def двигаться(self, пункт_назначения: str) -> None:
        """
        Начинает движение в указанный пункт назначения.

        Args:
            пункт_назначения (str): Название пункта назначения.

        Returns:
            None

        Examples:
            >>> class Автомобиль(ТранспортноеСредство):
            ...     def __init__(self, скорость: float, вместимость: int, тип_двигателя: str):
            ...         super().__init__(скорость, вместимость, тип_двигателя)
            ...     def двигаться(self, пункт_назначения: str) -> None:
            ...         pass  # Заглушка для примера
            >>> car = Автомобиль(200.0, 5, "бензин")
            >>> car.двигаться("Москва")
        """
        pass

    @abstractmethod
    def остановиться(self) -> None:
        """
        Останавливает транспортное средство.

        Returns:
            None
        """
        pass

class Организация(ABC):
    """
    Абстрактный класс, представляющий организацию.
    """

    @abstractmethod
    def __init__(self, название: str, количество_сотрудников: int, сфера_деятельности: str):
        """
        Инициализирует организацию.

        Args:
            название (str): Название организации.
            количество_сотрудников (int): Количество сотрудников. Должно быть положительным.
            сфера_деятельности (str): Сфера деятельности организации (например, "IT", "финансы").

        Raises:
            ValueError: Если количество сотрудников не является положительным числом.
        """
        if количество_сотрудников <= 0:
            raise ValueError("Количество сотрудников должно быть положительным числом.")

        self.название: str = название
        self.количество_сотрудников: int = количество_сотрудников
        self.сфера_деятельности: str = сфера_деятельности

    @abstractmethod
    def нанять_сотрудника(self, должность: str) -> None:
        """
        Нанимает нового сотрудника на указанную должность.

        Args:
            должность (str): Название должности.

        Returns:
            None
        """
        pass

    @abstractmethod
    def уволить_сотрудника(self, имя_сотрудника: str) -> None:
        """
        Увольняет сотрудника из организации.

        Args:
            имя_сотрудника (str): Имя сотрудника, которого нужно уволить.

        Returns:
            None

        Examples:
            >>> class Компания(Организация):
            ...     def __init__(self, название: str, количество_сотрудников: int, сфера_деятельности: str):
            ...         super().__init__(название, количество_сотрудников, сфера_деятельности)
            ...     def нанять_сотрудника(self, должность: str) -> None:
            ...         pass
            ...     def уволить_сотрудника(self, имя_сотрудника: str) -> None:
            ...         pass
            >>> company = Компания("Acme Corp", 100, "IT")
            >>> company.уволить_сотрудника("John Doe")
        """
        pass

class Алгоритм(ABC):
    """
    Абстрактный класс, представляющий алгоритм.
    """

    @abstractmethod
    def __init__(self, название: str, сложность: str, область_применения: str):
        """
        Инициализирует алгоритм.

        Args:
            название (str): Название алгоритма.
            сложность (str): Сложность алгоритма (например, "O(n)", "O(log n)").
            область_применения (str): Область применения алгоритма (например, "сортировка", "поиск").
        """
        self.название: str = название
        self.сложность: str = сложность
        self.область_применения: str = область_применения

    @abstractmethod
    def выполнить(self, входные_данные: list) -> list:
        """
        Выполняет алгоритм над входными данными.

        Args:
            входные_данные (list): Список входных данных.

        Returns:
            list: Список выходных данных (результат выполнения алгоритма).

        Examples:
            >>> class Сортировка(Алгоритм):
            ...     def __init__(self, название: str, сложность: str, область_применения: str):
            ...         super().__init__(название, сложность, область_применения)
            ...     def выполнить(self, входные_данные: list) -> list:
            ...         return sorted(входные_данные) # Пример реализации сортировки
            >>> sort_algorithm = Сортировка("Быстрая сортировка", "O(n log n)", "сортировка")
            >>> data = [3, 1, 4, 1, 5, 9, 2, 6]
            >>> sorted_data = sort_algorithm.выполнить(data)
            >>> print(sorted_data)
            [1, 1, 2, 3, 4, 5, 6, 9]
        """
        pass